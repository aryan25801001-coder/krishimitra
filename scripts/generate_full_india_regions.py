def build_regions_json():
    regions = []
    for state_data in INDIA_GEOGRAPHIC_DATA:
        state_name = state_data["state"]
        state_code = state_data["stateCode"]
        for dist in state_data["districts"]:
            d_name, zone, lat, lon, soil = dist
            regions.append({
                "state": state_name,
                "district": d_name,
                "stateCode": state_code,
                "agroClimaticZone": zone,
                "latitude": lat,
                "longitude": lon,
                "primarySoilType": soil
            })
    return regions

